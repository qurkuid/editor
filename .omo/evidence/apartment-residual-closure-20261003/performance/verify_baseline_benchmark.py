#!/usr/bin/env python3
"""Guard the source-copy performance baseline without editing product files."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any


REPO = Path(__file__).resolve().parents[4]
ROOT = REPO / ".omo/evidence/apartment-residual-closure-20261003/performance"
PARENT = ROOT.parent / "baseline-parent"
MANIFEST = PARENT / "baseline-manifest.json"
INPUTS = ROOT / "inputs/manifest-current-normalized-walls.json"
# Keep the stress-inclusive artifact as the guarded baseline. The shorter
# same-label artifact is a real-only timing sample and may be regenerated by a
# caller that does not request stress; it is retained separately.
OUTPUT = ROOT / "baseline-v15-current-0b926754-stress-100-500-1000-final-detector-benchmark.json"
OUT_VERIFICATION = ROOT / "baseline-verification.json"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def check(condition: bool, message: str) -> None:
    if not condition:
        raise SystemExit(message)


def main() -> int:
    parent = json.loads(MANIFEST.read_text())
    check(parent.get("count") == 168, f"parent manifest count is {parent.get('count')}, expected 168")
    check(parent.get("verified") is True, "parent manifest is not marked verified")
    source_entries = {entry["path"]: entry for entry in parent["files"] if entry.get("kind") == "source"}
    core_rel = "packages/core/src/lib/space-detection.ts"
    importer_rel = "apps/editor/lib/apt-vector-scene.ts"
    core_expected = source_entries[core_rel]["sha256"]
    importer_expected = source_entries[importer_rel]["sha256"]
    core_snapshot = PARENT / "source-snapshots" / core_rel
    importer_snapshot = PARENT / "source-snapshots" / importer_rel
    check(sha256(core_snapshot) == core_expected, "core source snapshot SHA mismatch")
    check(sha256(importer_snapshot) == importer_expected, "importer source snapshot SHA mismatch")

    kinds: dict[str, int] = {}
    external_mismatches: list[str] = []
    for entry in parent["files"]:
        kinds[entry["kind"]] = kinds.get(entry["kind"], 0) + 1
        # Source files can legitimately move on the shared dirty checkout after
        # the freeze. Validate their immutable evidence copies; raw/imported/
        # evaluation artifacts remain external immutable inputs.
        path = (
            PARENT / "source-snapshots" / entry["path"]
            if entry["kind"] == "source"
            else REPO / entry["path"]
        )
        if not path.exists() or sha256(path) != entry["sha256"]:
            external_mismatches.append(entry["path"])
    check(not external_mismatches, f"parent freeze mismatches: {external_mismatches[:3]}")

    inputs = json.loads(INPUTS.read_text())
    check(len(inputs.get("cases", [])) == 44, "normalized input manifest must contain 44 cases")
    input_mismatches: list[str] = []
    for case in inputs["cases"]:
        path = REPO / case["snapshotPath"]
        if not path.exists() or sha256(path) != case["snapshotSha256"]:
            input_mismatches.append(case["planId"])
    check(not input_mismatches, f"normalized input mismatches: {input_mismatches[:3]}")

    output = json.loads(OUTPUT.read_text())
    check(output["resolvedRoute"] == {"model": "gpt-5.6-luna", "reasoningEffort": "max"}, "resolved route mismatch")
    check(output["sourceSnapshot"]["core"]["actualSha256"] == core_expected, "benchmark core SHA mismatch")
    check(output["sourceSnapshot"]["importer"]["actualSha256"] == importer_expected, "benchmark importer SHA mismatch")
    check(output["input"]["importedCaseCount"] == 44, "benchmark imported count mismatch")
    check(output["protocol"]["warmupRounds"] == 2, "warmup protocol mismatch")
    check(output["protocol"]["timedRoundsPerCase"] == 12, "timed-round protocol mismatch")
    check(output["importerVerification"]["matchCount"] == 44, "importer verification did not match all 44 cases")
    aggregate = output["aggregate"]
    check(aggregate["realCaseCount"] == 44, "real case count mismatch")
    check(aggregate["realCompletedCases"] == 44, "real benchmark did not complete all cases")
    check(aggregate["roundErrorCount"] == 0, "benchmark round errors present")
    check(aggregate["geometryFailureCount"] == 0, "geometry idempotence failures present")
    check(output["beforeAfterRatio"]["status"] == "NOT_MEASURED", "baseline accidentally claims a ratio")
    check(len(output["cases"]) == 47, "stress run should contain 44 real + 3 synthetic cases")
    check(output["protocol"]["syntheticCounts"] == [100, 500, 1000], "synthetic stress protocol mismatch")
    check(all(case["status"] == "PASS" for case in output["cases"]), "one or more benchmark cases failed")

    verification: dict[str, Any] = {
        "schemaVersion": "apartment-residual-performance-baseline-verification-v1",
        "resolvedRoute": output["resolvedRoute"],
        "baselineParentManifest": str(MANIFEST.relative_to(REPO)),
        "baselineParentManifestCount": parent["count"],
        "baselineParentKinds": kinds,
        "sourceSnapshots": {
            "count": len(source_entries),
            "allVerified": True,
            "core": {"path": str(core_snapshot.relative_to(REPO)), "sha256": core_expected, "verified": True},
            "importer": {"path": str(importer_snapshot.relative_to(REPO)), "sha256": importer_expected, "verified": True},
        },
        "inputs": {"manifest": str(INPUTS.relative_to(REPO)), "caseCount": 44, "verified": True},
        "benchmark": {
            "output": str(OUTPUT.relative_to(REPO)),
            "outputSha256": sha256(OUTPUT),
            "inputManifestSha256": sha256(INPUTS),
            "realCaseCount": aggregate["realCaseCount"],
            "syntheticCounts": output["protocol"]["syntheticCounts"],
            "timedCalls": aggregate["timedCalls"],
            "importerMatches": output["importerVerification"]["matchCount"],
            "roundErrors": aggregate["roundErrorCount"],
            "geometryFailures": aggregate["geometryFailureCount"],
            "beforeAfterRatio": output["beforeAfterRatio"],
            "verified": True,
        },
    }
    OUT_VERIFICATION.write_text(json.dumps(verification, indent=2, sort_keys=True) + "\n")
    print(json.dumps(verification, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
